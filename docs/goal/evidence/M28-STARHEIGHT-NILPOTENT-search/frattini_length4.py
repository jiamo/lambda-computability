#!/usr/bin/env python3
"""R3 (b): for which words w does the prime-index method apply to L(w, k, p) directly?

`height_one_of_abelian_normal_exponent_prime` (Start/StarHeightElementary.lean) covers every group G
with an abelian normal subgroup N such that G/N is abelian of exponent p.  The smallest such N is
the Frattini subgroup Phi(G) = [G,G] G^p of the p-group G, so the method applies iff Phi(G) is
abelian.

For each word w (up to renaming letters and reversal) we compute the syntactic group of
L(w, 0, p): the transition group of the minimal automaton whose states are the vectors
(scount of the prefixes of w, mod p), accepting when scount w = 0.  (For p >= |w| + 1 the
languages L(w, k, p) for the various k share this group.)  We report |G|, |Phi(G)|, and whether
Phi(G) is abelian.

Usage: python3 frattini_length4.py [p ...]      (default 3 5)
"""
import itertools
import sys


def automaton(w, p):
    letters = sorted(set(w))
    n = len(w)
    start = (1,) + (0,) * n
    states = {start: 0}
    order = [start]
    trans = {a: [] for a in letters}
    i = 0
    while i < len(order):
        v = order[i]
        for a in letters:
            u = list(v)
            for j in range(n, 0, -1):
                if w[j - 1] == a:
                    u[j] = (u[j] + u[j - 1]) % p
            u = tuple(u)
            if u not in states:
                states[u] = len(order)
                order.append(u)
            trans[a].append(states[u])
        i += 1
    acc = [v[n] for v in order]
    return letters, order, trans, acc


def minimize(letters, order, trans, acc):
    part = list(acc)
    while True:
        sig = [(part[s],) + tuple(part[trans[a][s]] for a in letters) for s in range(len(order))]
        ids = {}
        new = [ids.setdefault(x, len(ids)) for x in sig]
        if len(ids) == len(set(part)):
            break
        part = new
    k = len(set(part))
    gens = []
    for a in letters:
        perm = [None] * k
        for s in range(len(order)):
            perm[part[s]] = part[trans[a][s]]
        gens.append(tuple(perm))
    return gens


def mul(f, g):  # first f then g
    return tuple(g[x] for x in f)


def inv(f):
    r = [0] * len(f)
    for i, x in enumerate(f):
        r[x] = i
    return tuple(r)


def closure(gens, ident):
    G = {ident}
    frontier = [ident]
    while frontier:
        nf = []
        for g in frontier:
            for s in gens:
                h = mul(g, s)
                if h not in G:
                    G.add(h)
                    nf.append(h)
        frontier = nf
    return G


def frattini_info(gens, p):
    k = len(gens[0])
    ident = tuple(range(k))
    G = closure(gens, ident)
    comms = set()
    Gl = list(G)
    # [G,G] is generated by commutators of generators and their conjugates; use all commutators
    # of generators with elements (normal closure computed by closure under conjugation below)
    for a in gens:
        for b in gens:
            comms.add(mul(mul(inv(a), inv(b)), mul(a, b)))
    powers = set()
    for g in gens:
        x = ident
        for _ in range(p):
            x = mul(x, g)
        powers.add(x)
    seeds = comms | powers
    # normal closure of seeds
    N = closure(list(seeds), ident)
    while True:
        extra = set()
        for n_ in list(seeds):
            for s in gens:
                c = mul(mul(inv(s), n_), s)
                if c not in N:
                    extra.add(c)
        if not extra:
            break
        seeds |= extra
        N = closure(list(seeds), ident)
    abelian = all(mul(a, b) == mul(b, a) for a in seeds for b in seeds)
    return len(G), len(N), abelian


def canon(w):
    def relabel(x):
        m = {}
        return tuple(m.setdefault(a, len(m)) for a in x)
    return min(relabel(w), relabel(tuple(reversed(w))))


if __name__ == "__main__":
    for p in [int(a) for a in sys.argv[1:]] or [3, 5]:
        seen = set()
        for L in (2, 3, 4):
            for w in itertools.product(range(4), repeat=L):
                c = canon(w)
                if c in seen:
                    continue
                seen.add(c)
                letters, order, trans, acc = automaton(c, p)
                gens = minimize(letters, order, trans, acc)
                g, n, ab = frattini_info(gens, p)
                name = ''.join('abcd'[a] for a in c)
                print(f"p={p} w={name:5s} |G|={g:8d} |Phi|={n:6d} Phi abelian={ab}")
                sys.stdout.flush()
