#!/usr/bin/env python3
"""Approach 1 by Schreier generators (not Lean-verified).

All components are permutation automata (good automata, letter counters mod N, fixed-letter base
counts).  Let G be the transition group of the target automaton T for shcount q mod 2 (8 points,
|G| = 128) and Im the image in G of the words that return every component to its start.  Im is
generated by the Schreier generators g_s x g_{s.x}^{-1} of the joint component orbit.  The
target is determined by the components iff val is constant on (t0 . Im) . g for every g in G.
[G : Im] measures how much of G the family sees.
"""
import sys
from collections import deque
from common import mul, inv, closure, shear_target

L3 = (0, 1, 2)


def target_group(q=(0, 0)):
    pts, lets, t0, val = shear_target(2, q, 2)
    e = tuple(range(len(pts)))
    return lets, t0, val, e


def image(components, tl, e):
    """components: list of (start, step); returns the subgroup Im of G and the orbit size"""
    s0 = tuple(c[0] for c in components)
    rep = {s0: e}
    todo = deque([s0])
    gens = set()
    while todo:
        s = todo.popleft()
        g = rep[s]
        for x in L3:
            t = tuple(c[1](si, x) for c, si in zip(components, s))
            gx = mul(g, tl[x])
            if t in rep:
                sg = mul(gx, inv(rep[t]))
                if sg != e:
                    gens.add(sg)
            else:
                rep[t] = gx
                todo.append(t)
    return closure(list(gens), e) if gens else frozenset([e]), len(rep)


def determined(Im, tl, t0, val, e):
    G = closure(tl, e)
    O = {s[t0] for s in Im}
    return all(len({val(g[o]) for o in O}) == 1 for g in G)


def perm_component(lets, base_counts=True):
    """good automaton; with base_counts also the parities of the letters x with 0.x = 0 read at 0"""
    if not base_counts:
        return (0, lambda s, x: lets[x][s])
    def step(s, x):
        st, k = s
        if st == 0 and lets[x][0] == 0:
            k = k ^ (1 << x)
        return (lets[x][st], k)
    return ((0, 0), step)


def counter(x, N):
    return (0, lambda s, y: (s + (y == x)) % N)


if __name__ == '__main__':
    tl, t0, val, e = target_group()
    G = closure(tl, e)
    print("|G| =", len(G))
    comps = [counter(x, 8) for x in L3]
    Im, n = image(comps, tl, e)
    print("letter counts mod 8: orbit", n, "|Im| =", len(Im), "determined", determined(Im, tl, t0, val, e))
