#!/usr/bin/env python3
"""Group-theoretic facts about shcount q mod 2 and scount abac mod 2 (not Lean-verified).

For each target: the transition group G, its order, the exponent, the subgroup N generated by
commutators and squares (= Frattini subgroup of a 2-group) and whether N is abelian, the number
of subgroups, and the coset test: G/H is good when its first returns are star-free or G/H is
abelian; D = intersection of the good H; the target is determined by Boolean combinations of good
coset automata of G iff D fixes the target value.
Usage: python3 group_facts.py [p]
"""
import sys
from functools import reduce
from common import *


def facts(name, pts, lets, start, val, do_subgroups=True):
    e = tuple(range(len(pts)))
    G = closure(lets, e)
    ords = {}
    for g in G:
        o = order(g)
        ords[o] = ords.get(o, 0) + 1
    p = 2 if len(G) & (len(G) - 1) == 0 else None
    gens = [mul(mul(mul(x, y), inv(x)), inv(y)) for x in G for y in G]
    if p:
        gens += [mul(x, x) for x in G]
    N = closure(list(set(gens)), e)
    Nab = all(mul(x, y) == mul(y, x) for x in N for y in N)
    S = frozenset(h for h in G if all(val(mul(g, h)[start]) == val(g[start]) for g in G))
    print(f"{name}: |G| = {len(G)}, element orders {dict(sorted(ords.items()))}, "
          f"|N| = {len(N)}, N abelian: {Nab}")
    if not do_subgroups:
        return
    subs = subgroups(G, e)
    good = []
    comm = closure(list({mul(mul(mul(x, y), inv(x)), inv(y)) for x in G for y in G}), e)
    for H in subs:
        delta, b = coset_automaton(G, H, lets, e)
        sf = starfree_returns(delta, b, len(lets))
        ab = comm <= H
        if sf or ab:
            good.append((len(G) // len(H), bool(sf), ab, H))
    D = reduce(lambda x, y: x & y, [t[3] for t in good], G)
    print(f"   subgroups {len(subs)}; good (index, starfree, abelian quotient): "
          f"{sorted({t[:3] for t in good})}; count {len(good)}; |D| = {len(D)}, D = N: {D == N}, "
          f"D fixes target: {D <= S}")


if __name__ == '__main__':
    p = int(sys.argv[1]) if len(sys.argv) > 1 else 2
    for q in [(A, l) for A in range(p) for l in range(p)]:
        facts(f"shcount {q} mod {p}", *shear_target(p, q, p), do_subgroups=(p == 2))
    facts(f"scount abac mod {p}", *scount_target([0, 1, 0, 2], p), do_subgroups=(p == 2))
    facts(f"scount abca mod {p}", *scount_target([0, 1, 2, 0], p), do_subgroups=False)
