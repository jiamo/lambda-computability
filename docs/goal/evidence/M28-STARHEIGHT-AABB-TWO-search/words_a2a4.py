# R3 (b)(iii): which counts L(w, k, 2), |w| = 4, have a syntactic group in A2A4 (an elementary abelian
# normal subgroup with abelian quotient of exponent 4), so that the W-test applies?
# For each word up to renaming: the syntactic group of {u : scount w u odd} (quotient of the UT5(F2)
# transition group), its order, membership in A2A4, and, for two-letter words, the W-test against the
# good families of c0_variety.py (WR = Z2 wr Z4, UT = UT4(F2), FA = abelian Frattini subgroup).
