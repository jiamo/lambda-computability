def elem(pairs):
    M = list(I5)
    for i, j in pairs: M[i] |= 1 << j
    return tuple(M)

def words4():
    out = []
    def rec(w, m):
        if len(w) == 4: out.append("".join("abcd"[i] for i in w)); return
        for i in range(m + 1): rec(w + [i], max(m, i + 1))
    rec([], 0)
    return out

def syn(w):
    letters = sorted(set(w))
    gens = [elem([(i, i + 1) for i in range(4) if w[i] == x]) for x in letters]
    G = {I5}; fr = [I5]
    while fr: fr = [y for x in fr for g in gens for y in [mmul(x, g)] if y not in G and not G.add(y)]
    F = {t for t in G if t[0] >> 4 & 1}
    stab = {n for n in G if all(mmul(e, n) in F for e in F)}
    N = [n for n in stab if all(mmul(mmul(minv(p), n), p) in stab for p in G)]
    rep = {}
    for t in G:
        if t not in rep:
            cos = [mmul(t, n) for n in N]; m = min(cos)
            for e in cos: rep[e] = m
    class Q:
        one = rep[I5]
        mul = staticmethod(lambda a, b: rep[mmul(a, b)])
        inv = staticmethod(lambda a: rep[minv(a)])
    elems = set(rep.values()); qg = [rep[g] for g in gens]
    # V = subgroup generated by commutators and 4th powers (normal: verbal)
    V = {Q.one}; frontier = [Q.one]
    seeds = {Q.mul(Q.mul(x, y), Q.inv(Q.mul(y, x))) for x in elems for y in elems} | \
            {Q.mul(Q.mul(x, x), Q.mul(x, x)) for x in elems}
    while frontier:
        frontier = [y for x in frontier for s in seeds for y in [Q.mul(x, s)] if y not in V and not V.add(y)]
    a2a4 = all(Q.mul(x, x) == Q.one for x in V) and all(Q.mul(x, y) == Q.mul(y, x) for x in V for y in V)
    return len(elems), len(letters), a2a4, Q, qg

for w in words4():
    order, n, a2a4, Q, qg = syn(w)
